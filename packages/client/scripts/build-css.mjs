// Compiles the UI's Tailwind styles into a module the UI adds to its shadow
// roots. Custom property registrations (@property) are split out: browsers
// ignore them inside a shadow root, so they are added to the document instead.
import { spawn, spawnSync } from 'node:child_process';
import { mkdirSync, readFileSync, watch, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const input = `${root}src/lib/ui/styles.css`;
const dir = `${root}src/lib/ui/generated`;
const css = `${dir}/styles.css`;
const bin = `${root}node_modules/.bin/tailwindcss`;
const watching = process.argv.includes('--watch');

mkdirSync(dir, { recursive: true });

function wrap() {
	let text;
	try {
		text = readFileSync(css, 'utf8');
	} catch {
		return;
	}
	const registrations = text.match(/@property\s+--[\w-]+\s*\{[^}]*\}/g) ?? [];
	const styles = registrations.reduce((rest, rule) => rest.replace(rule, ''), text);
	writeFileSync(`${dir}/styles.js`,
		`// Generated by scripts/build-css.mjs.\nexport const styles = ${JSON.stringify(styles)};\nexport const properties = ${JSON.stringify(registrations.join(''))};\n`);
	writeFileSync(`${dir}/styles.d.ts`, 'export const styles: string;\nexport const properties: string;\n');
}

const args = ['-i', input, '-o', css, '--minify'];
if (watching) {
	spawn(bin, [...args, '--watch'], { stdio: 'inherit' });
	let timer;
	watch(dir, (_, name) => {
		if (name !== 'styles.css') return;
		clearTimeout(timer);
		timer = setTimeout(wrap, 50);
	});
} else {
	const result = spawnSync(bin, args, { stdio: 'inherit' });
	if (result.status !== 0) process.exit(result.status ?? 1);
	wrap();
}
